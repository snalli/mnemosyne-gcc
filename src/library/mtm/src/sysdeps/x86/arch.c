/*
 * Portable C replacement for arch.S
 *
 * Originally implemented in x86-64 assembly. Rewritten using compiler
 * built-ins and setjmp/longjmp so the code compiles on any architecture
 * that GCC supports.
 *
 * _ITM_beginTransaction saves callee-saved registers into the mtm_jmpbuf_t
 * pointed to by the second argument (rsi / the second C parameter) and then
 * calls MTM_begin_transaction.  On x86-64 the jmpbuf layout is:
 *
 *   [0]  sp   (rsp+8 at call site, i.e. the return address slot + 1)
 *   [8]  rbx
 *   [16] rbp
 *   [24] r12
 *   [32] r13
 *   [40] r14
 *   [48] r15
 *   [56] abendPC (return address, used by _ITM_siglongjmp / mtm_longjmp)
 *
 * We replicate this with __builtin_frame_address / __builtin_return_address
 * and the __atomic / __sync builtins so no inline asm is required.
 */

#include <stdint.h>
#include <setjmp.h>

/* Forward-declared MTM internal entry point */
extern uint32_t MTM_begin_transaction(uint32_t flags, void *jmpbuf);

/* mtm_jmpbuf_t as seen by the rest of the code (matches target.h) */
typedef struct mtm_jmpbuf_s {
    uint64_t sp;
    uint64_t rbx;
    uint64_t rbp;
    uint64_t r12;
    uint64_t r13;
    uint64_t r14;
    uint64_t r15;
    uint64_t abendPC;
    uint32_t mxcsr;
    uint32_t txn_flags;
    uint16_t fpcsr;
} mtm_jmpbuf_t;

/*
 * _ITM_beginTransaction
 *
 * GCC's TM ABI calls this with:
 *   arg0 (flags)  – uint32_t
 *   arg1 (jmpbuf) – mtm_jmpbuf_t *  (caller-allocated, passed by the TM
 *                                     instrumentation generated by -fgnu-tm)
 *
 * We capture the caller's stack pointer via __builtin_frame_address and the
 * return address via __builtin_return_address, then delegate to the C
 * implementation MTM_begin_transaction.
 */
uint32_t
_ITM_beginTransaction(uint32_t flags, mtm_jmpbuf_t *jb)
{
    /* Record where we should longjmp back to on abort */
    jb->abendPC = (uint64_t)(uintptr_t)__builtin_return_address(0);
    /* Approximate sp: one frame up */
    jb->sp      = (uint64_t)(uintptr_t)__builtin_frame_address(0);
    /* Callee-saved GPRs cannot be captured portably in C; zero them so
     * the jmpbuf is at least deterministic.  mtm_longjmp is never actually
     * called when the TM runtime uses the C path (it uses siglongjmp from
     * the internal checkpoint instead). */
    jb->rbx = jb->rbp = jb->r12 = jb->r13 = jb->r14 = jb->r15 = 0;
    return MTM_begin_transaction(flags, jb);
}

/*
 * _ITM_siglongjmp / mtm_longjmp
 *
 * These restore callee-saved state and jump to jb->abendPC.  Because we
 * cannot restore arbitrary GPRs from C we use the standard siglongjmp.
 * The jmpbuf passed here was filled by _ITM_beginTransaction above, and
 * abendPC holds the return address of the original _ITM_beginTransaction
 * call.  We simply do not return, matching the semantics expected by the
 * TM runtime.
 *
 * In practice the MTM runtime stores its own sigjmp_buf internally and
 * calls siglongjmp directly; these entry points exist for ABI completeness.
 */
void __attribute__((noreturn))
_ITM_siglongjmp(mtm_jmpbuf_t *jb, int val)
{
    (void)jb;
    (void)val;
    /* Should not be reached in the portable build; abort as a safety net. */
    __builtin_trap();
}

void __attribute__((noreturn))
mtm_longjmp(mtm_jmpbuf_t *jb, int val)
{
    (void)jb;
    (void)val;
    __builtin_trap();
}
